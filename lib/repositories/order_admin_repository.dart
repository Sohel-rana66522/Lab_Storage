/// What an approval attempt did.
class ApprovalOutcome {
  const ApprovalOutcome({
    required this.transactionIds,
    this.alreadyApproved = false,
    this.confirmedAfterError = false,
  });

  /// Ledger entries generated by the approval, in item order.
  final List<String> transactionIds;

  /// The order had already been approved earlier. NOTHING was written this time.
  final bool alreadyApproved;

  /// The connection dropped while committing; the order was re-read from the server and found
  /// approved by this admin, so the approval did go through.
  final bool confirmedAfterError;
}

/// Laboratory-side order processing.
///
/// Approving an order is ONE Firestore transaction that
///   • re-reads the order and refuses unless it is still `Pending`,
///   • confirms the signed-in user is an admin,
///   • re-reads every requested chemical and validates ALL quantities,
///   • then writes every stock update, every ledger entry and the order's new status together.
/// If anything fails, Firestore commits none of it.
///
/// Stock maths is NOT re-implemented here: it is [TransactionRepository.planEntry] and
/// [TransactionRepository.stageEntry], the same code manual entries use.
class OrderAdminRepository {
  OrderAdminRepository(this._db);
  final FirebaseFirestore _db;

  CollectionReference<Map<String, dynamic>> get _col => _db.collection(Col.orders);

  static const maxReasonLength = 500;

  /// Matches OrderRepository.maxItems and firestore.rules (document-access limit per commit).
  static const maxItemsPerApproval = 7;

  static bool _hasAdminRole(Map<String, dynamic>? userDoc) =>
      UserRole.parse(userDoc?['role'] as String?) == UserRole.admin;

  void _log(String message, [Object? error, StackTrace? stack]) =>
      developer.log(message, name: 'OrderAdminRepository', error: error, stackTrace: stack);

  // ---------------------------------------------------------------------------
  // Reading
  // ---------------------------------------------------------------------------

  /// Newest first. Filtering by status is done in memory so no composite index is needed;
  /// a laboratory handles a modest number of orders.
  Stream<List<OrderModel>> watchAll({int limit = 300}) => _col
      .orderBy('createdAt', descending: true)
      .limit(limit)
      .snapshots()
      .map((s) => s.docs.map(OrderModel.fromFirestore).toList());

  Stream<OrderModel?> watchOne(String orderId) => _col
      .doc(orderId)
      .snapshots()
      .map((s) => s.exists ? OrderModel.fromFirestore(s) : null);

  /// Whether [uid] holds the ADMIN role (`users/{uid}.role == 'ADMIN'`). Used to show or hide
  /// the Approve / Reject buttons. It is a convenience only: the security rules decide.
  Future<bool> isAdmin(String uid) async {
    try {
      final snap = await _db.collection(Col.users).doc(uid).get();
      return snap.exists && _hasAdminRole(snap.data());
    } on FirebaseException catch (e, st) {
      _log('isAdmin check failed', e, st);
      return false;
    }
  }

  // ---------------------------------------------------------------------------
  // Approve
  // ---------------------------------------------------------------------------

  /// Deterministic ledger id for item [index] (0-based) of [orderId]: `LAB-ABCD2345-1`, `-2`…
  /// Because the id is fixed, a retry can only ever target the SAME documents; combined with
  /// the Pending check and the rules (ledger entries cannot be updated) a second deduction
  /// is impossible.
  static String ledgerIdFor(String orderId, int index) => '$orderId-${index + 1}';

  Future<ApprovalOutcome> approve({required User actor, required String orderId}) async {
    final id = orderId.trim();
    if (id.isEmpty) throw AppException('Order not found.');
    try {
      return await _approveInTransaction(actor, id);
    } on FirebaseException catch (e, st) {
      _log('approve($id) failed: ${e.code}', e, st);
      final resolved = await _explainApprovalFailure(actor, id, e);
      if (resolved is ApprovalOutcome) return resolved;
      throw resolved;
    }
  }

  Future<ApprovalOutcome> _approveInTransaction(User actor, String orderId) async {
    final orderRef = _col.doc(orderId);
    final adminRef = _db.collection(Col.users).doc(actor.uid);
    var alreadyApproved = false;
    var ids = <String>[];

    await _db.runTransaction((tx) async {
      // The closure can run more than once (Firestore retries on contention), so it must
      // start from a clean slate every time.
      alreadyApproved = false;
      ids = <String>[];

      // ---- 1. READS (Firestore requires every read before the first write) -------------
      final orderSnap = await tx.get(orderRef);
      if (!orderSnap.exists) throw AppException('Order not found. It may have been removed.');
      final order = OrderModel.fromFirestore(orderSnap);

      final adminSnap = await tx.get(adminRef);
      if (!adminSnap.exists || !_hasAdminRole(adminSnap.data())) {
        throw AppException('Only laboratory admins can approve orders.');
      }

      if (order.isApproved) {
        // Idempotent: a repeat tap, a refresh or a retry after a dropped connection lands
        // here and writes nothing.
        alreadyApproved = true;
        ids = order.transactionIds;
        return;
      }
      if (order.isRejected) {
        throw AppException('This order was already rejected and can no longer be approved.');
      }
      if (!order.isPending) {
        throw AppException('This order is "${order.status}" and cannot be approved.');
      }

      final structural = checkShape(order);
      if (structural != null) throw AppException(structural);

      final chemRefs = [
        for (final item in order.items) _db.collection(Col.chemicals).doc(item.chemicalId),
      ];
      final chemSnaps = <DocumentSnapshot<Map<String, dynamic>>>[
        for (final ref in chemRefs) await tx.get(ref),
      ];

      // ---- 2. VALIDATE EVERYTHING before writing anything ------------------------------
      final problems = <String>[];
      final plans = <StockPlan?>[];
      final chemicals = <ChemicalModel?>[];
      for (var i = 0; i < order.items.length; i++) {
        final item = order.items[i];
        final snap = chemSnaps[i];
        if (!snap.exists) {
          problems.add('${item.chemicalName}: this chemical no longer exists in the archive.');
          plans.add(null);
          chemicals.add(null);
          continue;
        }
        final chem = ChemicalModel.fromFirestore(snap);
        chemicals.add(chem);
        try {
          plans.add(TransactionRepository.planEntry(
            chem: chem,
            type: TxType.stockOut,
            quantity: item.requestedQuantity,
            unit: item.unit,
          ));
        } on AppException catch (e) {
          plans.add(null);
          problems.add('${item.chemicalName}: ${e.message}');
        } on ArgumentError catch (_) {
          plans.add(null);
          problems.add('${item.chemicalName}: ${item.unit} is not a valid unit for this chemical.');
        }
      }
      if (problems.isNotEmpty) {
        // Nothing has been written, so nothing needs undoing.
        throw AppException('The order cannot be approved:\n${problems.join('\n')}');
      }

      // ---- 3. WRITES: stock + ledger for each item, then the order itself --------------
      final now = DateTime.now();
      final actorName = Fmt.accountName(actor);
      for (var i = 0; i < order.items.length; i++) {
        final item = order.items[i];
        final chem = chemicals[i]!;
        final plan = plans[i]!;
        final txRef = _db.collection(Col.transactions).doc(ledgerIdFor(order.id, i));
        final entry = TransactionModel(
          id: txRef.id,
          chemicalId: chem.id,
          chemicalName: chem.name,
          chemicalFormula: chem.formula,
          categoryId: chem.categoryId,
          type: TxType.stockOut,
          quantity: plan.quantity,
          unit: chem.unit,
          enteredQuantity: item.requestedQuantity,
          enteredUnit: item.unit,
          balanceAfter: plan.newStock,
          studentId: order.clientId,
          studentName: order.clientName,
          purpose: 'Client order ${order.id}',
          remarks: 'Supervisor: ${order.supervisorName}',
          orderId: order.id,
          date: now,
          createdBy: actor.uid,
          createdByName: actorName,
        );
        TransactionRepository.stageEntry(
          tx,
          chemRef: chemRefs[i],
          txRef: txRef,
          entry: entry,
          plan: plan,
        );
        ids.add(txRef.id);
      }

      tx.update(orderRef, {
        'status': OrderStatus.approved,
        'approvedAt': FieldValue.serverTimestamp(),
        'approvedBy': actor.uid,
        'approvedByName': actorName,
        'transactionIds': ids,
        'updatedAt': FieldValue.serverTimestamp(),
      });
    });

    _log(alreadyApproved
        ? 'approve($orderId): already approved, nothing written'
        : 'approve($orderId): approved by ${actor.uid}, ${ids.length} ledger entries');
    return ApprovalOutcome(transactionIds: List.unmodifiable(ids), alreadyApproved: alreadyApproved);
  }

  /// Problems with the order document itself that no amount of stock can fix.
  static String? checkShape(OrderModel order) {
    if (order.items.isEmpty) return 'This order has no items.';
    if (order.items.length > maxItemsPerApproval) {
      return 'This order has ${order.items.length} chemicals; at most $maxItemsPerApproval can be '
          'approved at once. Reject it and ask the client to split it into smaller orders.';
    }
    final seen = <String>{};
    for (final item in order.items) {
      if (item.chemicalId.trim().isEmpty) {
        return 'An item in this order has no chemical reference. Reject it and ask the client to resubmit.';
      }
      if (!seen.add(item.chemicalId)) {
        return '${item.chemicalName} appears twice in this order. '
            'Reject it and ask the client to resubmit.';
      }
      if (!item.requestedQuantity.isFinite || item.requestedQuantity <= 0) {
        return '${item.chemicalName} has an invalid quantity.';
      }
      if (item.unit.trim().isEmpty) return '${item.chemicalName} has no unit.';
    }
    return null;
  }

  /// Turns a Firestore failure into either an [AppException] the admin can act on, or — when
  /// the connection dropped but the commit turned out to have succeeded — an [ApprovalOutcome].
  /// Because a dropped connection means the commit may or may not have happened, the order is
  /// read from the server before anything is reported.
  Future<Object> _explainApprovalFailure(User actor, String orderId, FirebaseException e) async {
    switch (e.code) {
      case 'permission-denied':
        return AppException('You do not have permission to approve orders. '
            'Ask a laboratory admin, or check that your account has the ADMIN role.');
      case 'not-found':
        return AppException('Order not found. It may have been removed.');
      case 'unavailable':
      case 'deadline-exceeded':
      case 'network-request-failed':
      case 'aborted':
      case 'cancelled':
      case 'unknown':
        return _verifyAfterUncertainFailure(actor, orderId, e);
      default:
        return AppException('Could not approve the order (${e.code}). Nothing was changed. '
            'Please try again.');
    }
  }

  Future<Object> _verifyAfterUncertainFailure(
      User actor, String orderId, FirebaseException cause) async {
    try {
      final snap = await _col.doc(orderId).get(const GetOptions(source: Source.server));
      if (!snap.exists) return AppException('Order not found. It may have been removed.');
      final order = OrderModel.fromFirestore(snap);
      if (order.isApproved) {
        // The commit DID succeed (or someone else approved it): report that, not an error.
        return ApprovalOutcome(
          transactionIds: order.transactionIds,
          alreadyApproved: order.approvedBy != actor.uid,
          confirmedAfterError: order.approvedBy == actor.uid,
        );
      }
      if (order.isRejected) {
        return AppException('This order has been rejected, so it was not approved.');
      }
      return AppException('The connection was interrupted and the order is still Pending. '
          'Nothing was deducted. Please try again.');
    } on FirebaseException catch (e, st) {
      _log('verification read failed after ${cause.code}', e, st);
      return AppException('The connection was interrupted and the result is unknown. '
          'Please reload the order and check its status BEFORE trying again.');
    }
  }

  // ---------------------------------------------------------------------------
  // Reject
  // ---------------------------------------------------------------------------

  /// Marks a Pending order Rejected. Never touches stock or the ledger.
  /// Returns true if this call rejected it, false if it was already rejected.
  Future<bool> reject({required User actor, required String orderId, String? reason}) async {
    final id = orderId.trim();
    if (id.isEmpty) throw AppException('Order not found.');
    final cleaned = (reason ?? '').trim();
    if (cleaned.length > maxReasonLength) {
      throw AppException('The reason must be $maxReasonLength characters or fewer.');
    }
    final orderRef = _col.doc(id);
    final adminRef = _db.collection(Col.users).doc(actor.uid);
    var changed = false;

    try {
      await _db.runTransaction((tx) async {
        changed = false;
        final orderSnap = await tx.get(orderRef);
        if (!orderSnap.exists) throw AppException('Order not found. It may have been removed.');
        final order = OrderModel.fromFirestore(orderSnap);

        final adminSnap = await tx.get(adminRef);
        if (!adminSnap.exists || !_hasAdminRole(adminSnap.data())) {
          throw AppException('Only laboratory admins can reject orders.');
        }

        if (order.isRejected) return; // idempotent
        if (order.isApproved) {
          throw AppException('This order was already approved. Approved orders cannot be rejected.');
        }
        tx.update(orderRef, {
          'status': OrderStatus.rejected,
          'rejectedAt': FieldValue.serverTimestamp(),
          'rejectedBy': actor.uid,
          'rejectedByName': Fmt.accountName(actor),
          if (cleaned.isNotEmpty) 'rejectionReason': cleaned,
          'updatedAt': FieldValue.serverTimestamp(),
        });
        changed = true;
      });
    } on FirebaseException catch (e, st) {
      _log('reject($id) failed: ${e.code}', e, st);
      switch (e.code) {
        case 'permission-denied':
          throw AppException('You do not have permission to reject orders.');
        case 'unavailable':
        case 'deadline-exceeded':
        case 'network-request-failed':
          // Same uncertainty as approval: check the server before reporting failure.
          try {
            final snap = await orderRef.get(const GetOptions(source: Source.server));
            if (snap.exists && OrderModel.fromFirestore(snap).isRejected) return true;
          } on FirebaseException catch (_) {}
          throw AppException('The connection was interrupted. Reload the order to see whether '
              'it was rejected before trying again.');
        default:
          throw AppException('Could not reject the order (${e.code}). Please try again.');
      }
    }
    _log(changed ? 'reject($id): rejected by ${actor.uid}' : 'reject($id): already rejected');
    return changed;
  }
}
